export const matchesActivityFilter = (
  event: BusinessEvent,
  filter: ActivityFilter,
) => {
  if (filter === "all") return true;
  if (filter === "operations") {
    return event.category === "operations" || event.category === "intelligence";
  }
  return event.category === filter;
};
