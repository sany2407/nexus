export const connectionMap = Object.fromEntries(
  connections.map((connection) => [connection.id, connection]),
);

export const connectionsForDepartment = (departmentId: string) =>
  connections.filter(
    (connection) =>
      connection.from === departmentId || connection.to === departmentId,
  );

export const relatedDepartments = (departmentId: string) => {
  const related = new Set<string>();
  for (const connection of connections) {
    if (connection.from === departmentId) related.add(connection.to);
    if (connection.to === departmentId) related.add(connection.from);
  }
  return [...related];
};
